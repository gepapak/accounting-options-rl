def families(n=4000):
    """Violating worlds. Each returns pairs on a cost grid; 'equivalent' families are single-floor-equivalent and cannot be seen by any test."""
    def grid():
        return np.array([0.0, 0.5, 1.0, 2.0, 4.0])

    def draw():
        return float(rng.choice([-1.0, 1.0])), 1.0 + 9.0 * rng.random()          # sigma, g

    fam = {}

    def cost_dependent_floor():
        c = grid(); s, g = draw(); a, b = -3.0 * rng.random(), (rng.choice([-1, 1])) * (0.2 + rng.random())
        return [(float(ck), float(max(s * g - ck, a + b * ck)), float(max(-s * g - ck, a + b * ck))) for ck in c]

    def magnitude_depends_on_cost():
        c = grid(); s, g = draw(); b = rng.choice([-1, 1]) * (0.1 + 0.5 * rng.random()); tau = -3.0 * rng.random()
        out = []
        for ck in c:
            gg = max(g + b * ck, 0.0)
            out.append((float(ck), float(max(s * gg - ck, tau)), float(max(-s * gg - ck, tau))))
        return out

    def two_write(e_over_c=None):
        c = grid(); s, g = draw(); e = 0.3 + 2.5 * rng.random()                  # equity: some tested fees below, some above
        out = []
        for ck in c:
            def r(sg):
                e1 = max(e - ck, 0.0); e2 = max(e1 + sg * g, 0.0)
                return e2 - e
            out.append((float(ck), float(r(s)), float(r(-s))))
        return out

    def ceiling_and_floor():
        c = grid(); s, g = draw(); tau = -3.0 * rng.random(); top = g * (0.2 + 0.7 * rng.random()) - 0.5
        return [(float(ck), float(min(max(s * g - ck, tau), top)), float(min(max(-s * g - ck, tau), top))) for ck in c]

    def branch_dependent_floor():
        c = grid(); s, g = draw(); t_up, t_dn = -3.0 * rng.random(), -3.0 * rng.random() + g * rng.random()
        return [(float(ck), float(max(s * g - ck, t_up if s > 0 else t_dn)), float(max(-s * g - ck, t_dn if s > 0 else t_up))) for ck in c]

    def independent_noise():
        c = grid(); s, g = draw(); tau = -3.0 * rng.random()
        return [(float(ck), float(max(s * g - ck, tau) + 0.05 * rng.standard_normal()), float(max(-s * g - ck, tau) + 0.05 * rng.standard_normal())) for ck in c]

    def hidden_fee_loss_censored():                           # the loss branch is censored: equivalent to a single-floor world with magnitude g - h
        c = grid(); s, g = draw(); h = 0.5 * g; tau = -0.2 * g * rng.random()
        return [(float(ck), float(max(s * g - h - ck, tau)), float(max(-s * g - h - ck, tau))) for ck in c]

    def hidden_fee_both_uncensored():                         # no floor binds: u + l = -2 (c + h) betrays the undeclared fee
        c = grid(); s, g = draw(); h = 0.5 * g
        return [(float(ck), float(s * g - h - ck), float(-s * g - h - ck)) for ck in c]

    def inflated_gross_credit():                              # equivalent to a single-floor world with magnitude 1.5 g
        c = grid(); s, g = draw(); tau = -3.0 * rng.random()
        return [(float(ck), float(max(1.5 * s * g - ck, tau)), float(max(-1.5 * s * g - ck, tau))) for ck in c]

    def constant_output():
        c = grid(); v = float(rng.random())
        return [(float(ck), v, v) for ck in c]

    for name, f, equivalent in (("cost-dependent floor", cost_dependent_floor, False), ("magnitude depends on the cost", magnitude_depends_on_cost, False),
                                ("two-write floor (fee below and above the equity)", two_write, False), ("ceiling and floor", ceiling_and_floor, False),
                                ("branch-dependent floor", branch_dependent_floor, False), ("independent reward noise", independent_noise, False),
                                ("hidden fixed fee, both branches uncensored", hidden_fee_both_uncensored, False),
                                ("hidden fixed fee, loss branch censored", hidden_fee_loss_censored, True), ("inflated gross credit", inflated_gross_credit, True),
                                ("constant output", constant_output, True)):
        old = new = 0
        for _ in range(n):
            pr = f()
            old += int(cost_shift_test(pr)[0])
            new += int(not single_floor_fit(pr, tol=1e-9)[0])
        fam[name] = dict(worlds=n, flagged_previous_test=old, flagged_exact_test=new, single_floor_equivalent=equivalent)
    return fam


