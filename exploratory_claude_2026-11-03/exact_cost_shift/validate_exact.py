"""Validation of single_floor_fit (exact_cost_shift.py) against an independent brute force, a false-alarm study and an adversarial benchmark.

    python validate_exact.py          # writes validate_exact_results.json next to this file

1. Exactness. On integer cost grids, every sequence of pairs generated by a single-floor world on a half-integer lattice is accepted, and every
   one-coordinate perturbation of such a sequence is accepted iff it is itself generated by some lattice world (independent set-membership
   brute force). A mismatch would mean that the finite candidate set of the algorithm is incomplete.
2. No false alarm. 100,000 random single-floor worlds over twelve orders of magnitude, with floating-point noise, none flagged.
3. Power. Violating worlds of several families: the previous test (twin_reward.cost_shift_test) and the exact test side by side. Families that
   a single-floor world could have produced (hidden fixed fee, inflated gross credit, constant output) are invisible to both, by construction.
4. The four evading environments and the incompatible grid of the independent review (theory_audit.py, 3 November 2026).
"""
from __future__ import annotations

import itertools
import json
import sys
from pathlib import Path

import numpy as np

