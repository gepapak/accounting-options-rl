def false_alarms(n=100_000, lo=-12.0, hi=6.0, noise_level=1e-13):
    """Random single-floor worlds with scales 10^lo .. 10^hi; the pairs carry floating-point noise of noise_level * scale (0 = exact)."""
    flagged_exact = flagged_old = 0
    examples = []
    for _ in range(n):
        scale = 10.0 ** rng.uniform(lo, hi)
        K = int(rng.integers(2, 9))
        c = np.sort(np.concatenate([[0.0] if rng.random() < 0.5 else [], scale * 10.0 ** rng.uniform(-3, 1, K)]))
        if rng.random() < 0.15:
            c = np.concatenate([c, c[:1]])                    # a tied cost
        g = 0.0 if rng.random() < 0.1 else scale * 10.0 ** rng.uniform(-3, 1)
        mode = rng.random()
        tau = -np.inf if mode < 0.15 else (-g * rng.random() if mode < 0.4 else scale * rng.uniform(-3, 3))
        tau = float(max(tau, -1e300))
        sigma = float(rng.choice([-1.0, 1.0]))
        pr = world(c, sigma, g, tau)
        noise = noise_level * scale
        if noise > 0:
            pr = [(ck, r + noise * rng.standard_normal(), p + noise * rng.standard_normal()) for ck, r, p in pr]
        ok, _, why = single_floor_fit(pr)
        if not ok:
            flagged_exact += 1
            if len(examples) < 5:
                examples.append(dict(pairs=pr, why=why, sigma=sigma, g=g, tau=tau))
        flagged_old += int(cost_shift_test(pr)[0])
    return dict(worlds=n, flagged_exact=flagged_exact, flagged_previous_test=flagged_old, examples=examples)


