sys.path[:0] = [str(HERE), str(CODE / "ACCOUNTING_OPTIONS_2026-10-14" / "twin_reward")]
from exact_cost_shift import single_floor_fit  # noqa: E402
from twin_reward import cost_shift_test  # noqa: E402

rng = np.random.default_rng(20261103)


def world(c, sigma, g, tau):
    """Pairs (c, r, r') of the single-floor world."""
    return [(float(ck), float(max(sigma * g - ck, tau)), float(max(-sigma * g - ck, tau))) for ck in c]


# --------------------------------------------------------------------------------------------------------------------------------------
def exactness():
    out = {}
    grids = ([0, 1], [0, 2], [1, 2, 4], [0, 1, 2], [0, 1, 3])
    G = [0.5 * i for i in range(0, 81)]                       # g in 0 .. 40 by halves (wide enough that no witness of a perturbed sequence leaves the lattice)
    T = [-np.inf] + [0.5 * i for i in range(-80, 81)]         # tau in -40 .. 40 by halves, and -inf
    for c in grids:
        gen = set()
        for sigma, g, tau in itertools.product((1.0, -1.0), G, T):
            gen.add(tuple((r, p) for _, r, p in world(c, sigma, g, tau)))
        gen_list = list(gen)
        n_gen_bad = 0
        for seq in gen_list:
            pairs = [(ck, r, p) for ck, (r, p) in zip(c, seq)]
            if not single_floor_fit(pairs)[0]:
                n_gen_bad += 1
        # perturbations of integer-valued generated sequences by +-1, +-2 in one coordinate
        n_pert = n_mismatch = n_accepted_nongenerated = 0
        for seq in gen_list:
            flat = [v for pr in seq for v in pr]
            if any((not np.isfinite(v)) or (not float(v).is_integer()) or abs(v) > 8 for v in flat):
                continue
            for i, dlt in itertools.product(range(len(flat)), (-2.0, -1.0, 1.0, 2.0)):
                f2 = list(flat)
                f2[i] += dlt
                seq2 = tuple((f2[2 * k], f2[2 * k + 1]) for k in range(len(c)))
                pairs = [(ck, r, p) for ck, (r, p) in zip(c, seq2)]
                got = single_floor_fit(pairs)[0]
                want = seq2 in gen
                n_pert += 1
                n_mismatch += int(got != want)
                n_accepted_nongenerated += int(got and not want)
        out[str(c)] = dict(generated_sequences=len(gen_list), generated_rejected=n_gen_bad, perturbations=n_pert, mismatches=n_mismatch,
                           accepted_but_not_generated=n_accepted_nongenerated)
    return out


