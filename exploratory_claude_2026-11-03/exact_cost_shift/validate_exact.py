def reviewer_cases():
    import gymnasium as gym

    class Probe(gym.Env):
        def __init__(self, mode):
            self.mode, self.cost, self.flip = mode, 0.0, False
            self.action_space = gym.spaces.Discrete(1)
            self.observation_space = gym.spaces.Box(-np.inf, np.inf, (1,), dtype=np.float32)

        def reverse_next_sign(self):
            self.flip = True

        def step(self, action):
            s = -1 if self.flip else 1
            c, g = self.cost, 10.0
            x = s * g - c
            r = {"cost_dependent_floor": max(x, c), "two_censors": min(max(x, 2.0), 2.0), "hidden_fixed_fee": max(x - 7.0, 0.0),
                 "inflated_magnitude": max(s * 15.0 - c, 0.0)}[self.mode]
            return np.zeros(1, dtype=np.float32), r, False, False, {"own_cost": c, "booked": x}

    from twin_reward import cost_shift_pairs
    out = {}
    for mode in ("cost_dependent_floor", "two_censors", "hidden_fixed_fee", "inflated_magnitude"):
        pairs = cost_shift_pairs(Probe(mode), 0, [0.0, 1.0, 2.0], lambda e, v: setattr(e, "cost", v))
        out[mode] = dict(pairs=pairs, flagged_previous_test=bool(cost_shift_test(pairs)[0]), flagged_exact_test=not single_floor_fit(pairs)[0],
                         exact_detail=single_floor_fit(pairs)[2])
    bad = [(0.0, 10.0, -10.0), (1.0, 0.0, 0.0)]
    out["incompatible_grid"] = dict(pairs=bad, flagged_previous_test=bool(cost_shift_test(bad)[0]), flagged_exact_test=not single_floor_fit(bad)[0],
                                    exact_detail=single_floor_fit(bad)[2])
    near = [(0.0, 5e-10, 5e-10), (1.0, 5e-10, 5e-10)]
    out["near_zero_true_world"] = dict(pairs=near, flagged_previous_test=bool(cost_shift_test(near)[0]), flagged_exact_test=not single_floor_fit(near)[0])
    return out


def main():
    res = dict(exactness=exactness())
    print("exactness:", json.dumps(res["exactness"]))
    res["false_alarms_noise_free"] = false_alarms(lo=-3.0, hi=3.0, noise_level=0.0)
    print("false alarms, exact arithmetic, scales 1e-3..1e3:", {k: v for k, v in res["false_alarms_noise_free"].items() if k != "examples"})
    res["false_alarms_with_noise"] = false_alarms(lo=-12.0, hi=6.0, noise_level=1e-13)
    print("false alarms, noise 1e-13 x scale, scales 1e-12..1e6:", {k: v for k, v in res["false_alarms_with_noise"].items() if k != "examples"})
    res["power"] = families()
    for k, v in res["power"].items():
        print(f"power | {k:52s} previous {v['flagged_previous_test']:5d}  exact {v['flagged_exact_test']:5d}  of {v['worlds']}  equivalent={v['single_floor_equivalent']}")
    res["reviewer_cases"] = reviewer_cases()
    for k, v in res["reviewer_cases"].items():
        print("reviewer case", k, "| previous flagged:", v["flagged_previous_test"], "| exact flagged:", v["flagged_exact_test"])
    (HERE / "validate_exact_results.json").write_text(json.dumps(res, indent=1, default=str), encoding="utf-8")


if __name__ == "__main__":
    main()
