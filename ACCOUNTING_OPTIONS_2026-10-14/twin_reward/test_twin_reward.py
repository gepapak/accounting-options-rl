"""Checks of twin_reward.py on a toy zero-floor environment (no learning, no data): `python test_twin_reward.py`.

1. The wrapper leaves the real trajectory untouched.
2. TIR equals the booked P&L on every step where the pair differs, and never errs by more than SPR (pathwise).
3. Where the pair coincides TIR is -c, so no gain is manufactured in an uninformative state.
4. Fair sign: the expectation of TIR and of SPR over the two signs equals the booked expectation -c (exact enumeration).
5. The reported reward is a censored observation: it never falls below the threshold, and it differs from the booked P&L only on credited steps.
6. The clone-free pooled-magnitude reward leaves the trajectory untouched and is fair-unbiased.
7. The cost-shift test of Assumption C raises no false alarm on the single-floor toy and flags every informative state with a fee above the
   account on a two-write toy (fee written first with its own floor, gross P&L second).
8. The exact test (single_floor_fit) accepts every pair sequence generated by a single-floor world on a lattice and accepts a perturbed
   sequence iff some lattice world generates it (independent brute force).
9. Violations from the fourth AI-assisted review: a cost-dependent floor and an incompatible grid are flagged by the exact test (the earlier
   implied-conditions check passed both); a hidden fixed fee on a censored loss branch, an inflated gross credit and a constant output pass,
   because a single-floor world produces the same pairs.
10. PMR's documented bias: with censored favourable draws in the pool the expected PMR reward exceeds the booked expectation (+4.5 against
   -0.5 in the stated example), in line with the bias identity E[PMR - x | history] = |q| d (m_bar - mu).
"""
from __future__ import annotations

import copy
import itertools

import gymnasium as gym
import numpy as np

from twin_reward import (PooledMagnitudeWrapper, TwinRewardWrapper, cost_shift_pairs, cost_shift_test, identified, single_floor_fit, spr,
                         tir, twin_bracket)

LEV = np.array([-16.0, -4.0, -1.0, 0.0, 1.0, 4.0, 16.0])


class ToyFloorEnv(gym.Env):
    """Zero floor: reported reward max(b, -equity), equity max(equity + b, 0); b = q * eps * m - c with c = fee*|q| + kappa*q^2."""
    metadata: dict = {}

    def __init__(self, seed=0, fee=0.1, kappa=0.02):
        self.rng = np.random.default_rng(seed)
        self.fee, self.kappa = fee, kappa
        self.action_space = gym.spaces.Discrete(len(LEV))
        self.observation_space = gym.spaces.Box(-np.inf, np.inf, shape=(1,), dtype=np.float32)
        self._flip = False
        self.force_sign = None
        self.equity = 1.0

    def reset(self, *, seed=None, options=None):
        if seed is not None:
            self.rng = np.random.default_rng(seed)
        self.equity = float(self.rng.uniform(0.0, 2.0))
        self._flip = False
        return np.array([self.equity], dtype=np.float32), {}

    def reverse_next_sign(self):
        self._flip = True

    def step(self, action):
        q = LEV[int(action)]
        m = abs(self.rng.normal(0.0, 0.3))
        eps = self.rng.choice([-1.0, 1.0]) if self.force_sign is None else self.force_sign
        eps = -eps if self._flip else eps
        self._flip = False
        c = self.fee * abs(q) + self.kappa * q * q
        b = q * eps * m - c
        r = max(b, -self.equity)
        self.equity = max(self.equity + b, 0.0)
        return (np.array([self.equity], dtype=np.float32), float(r), False, False,
                {"own_cost": c, "booked": b, "position": float(q), "gross_sign": float(np.sign(q) * eps)})


class ToyTwoWriteEnv(ToyFloorEnv):
    """Two floored cash writes: the fee is written first and floored (an account that cannot pay the fee is not charged for the unpaid part),
    then the gross P&L is written and floored. The reward is the change of the account; the booked P&L books the whole fee."""

    def step(self, action):
        q = LEV[int(action)]
        m = abs(self.rng.normal(0.0, 0.3))
        eps = self.rng.choice([-1.0, 1.0]) if self.force_sign is None else self.force_sign
        eps = -eps if self._flip else eps
        self._flip = False
        c = self.fee * abs(q) + self.kappa * q * q
        gross = q * eps * m
        e0 = self.equity
        self.equity = max(max(e0 - c, 0.0) + gross, 0.0)
        return (np.array([self.equity], dtype=np.float32), float(self.equity - e0), False, False,
                {"own_cost": c, "booked": gross - c, "position": float(q), "gross_sign": float(np.sign(q) * eps)})


def cost_shift_checks(rng):
    """7. The cost-shift test: no false alarm on the single-floor toy, every informative state with a fee above the account flagged on the two-write toy."""
    fees = [0.0, 0.05, 0.1, 0.2, 0.4, 0.8, 1.6, 3.2]
    set_fee = lambda e, v: setattr(e, "fee", v)  # noqa: E731
    stats = {}
    for name, cls in (("single floor", ToyFloorEnv), ("two writes", ToyTwoWriteEnv)):
        flagged_binding = binding = flagged_other = other = 0
        for _ in range(600):
            env = cls(seed=int(rng.integers(1e9)), fee=0.1, kappa=0.02)
            env.reset()
            env.equity = float(rng.choice([0.0, 1e-3, 0.02, 0.1, 0.5, 2.0, 50.0, 500.0]))      # the last two can pay every tested fee
            a = int(rng.integers(0, len(LEV)))
            if LEV[a] == 0.0:
                continue
            pairs = cost_shift_pairs(env, a, fees, set_fee)
            violated, _ = cost_shift_test(pairs)
            informative = any(abs(r - rp) > 1e-9 for _, r, rp in pairs)
            fee_exceeds = max(c for c, _, _ in pairs) > env.equity + 1e-12
            if fee_exceeds and informative:
                binding += 1
                flagged_binding += int(violated)
            elif not fee_exceeds:
                other += 1
                flagged_other += int(violated)
        stats[name] = (flagged_binding, binding, flagged_other, other)
    fb, b, fo, o = stats["single floor"]
    assert fo == 0 and fb == 0, "false alarm on the single-floor environment"
    assert o > 50 and stats["two writes"][3] > 50, "no state in which the account can pay every tested fee: the no-false-alarm check would be empty"
    fb2, b2, fo2, o2 = stats["two writes"]
    assert b2 > 50 and fb2 == b2, "an informative state with a fee above the account was not flagged on the two-write environment"
    assert fo2 == 0, "false alarm on the two-write environment where the account can pay every tested fee"
    # pure function: a few hand-made pair sets
    tau, g = 0.5, 3.0
    single = [(c, max(g - c, tau), max(-g - c, tau)) for c in (0.0, 1.0, 2.0, 5.0, 8.0)]        # censored from c = 2.5 on
    assert cost_shift_test(single) == (False, "consistent with a single monotone censor")
    e = 0.2
    two = [(c, max(g, 0.0) - e, -e) for c in (1.0, 2.0, 5.0)]                                    # fee above the equity: pair (g - e, -e) at every cost
    assert cost_shift_test(two)[0], "the two-write pair family was not flagged"
    print(f"7 ok: cost-shift test: single floor {fb}/{b} binding and {fo}/{o} other states flagged; two writes {fb2}/{b2} binding and {fo2}/{o2} other states flagged")


def world(costs, sigma, g, tau):
    return [(float(c), float(max(sigma * g - c, tau)), float(max(-sigma * g - c, tau))) for c in costs]


def exactness_checks():
    """8. single_floor_fit against an independent brute force on a half-integer lattice (g in 0..20, tau in -20..20 and -inf)."""
    n_gen = n_pert = 0
    for costs in ([0, 1], [0, 1, 3], [1, 2, 4]):
        gen = set()
        for sigma, g2, t2 in itertools.product((1.0, -1.0), range(0, 41), [None] + list(range(-40, 41))):
            tau = -np.inf if t2 is None else 0.5 * t2
            gen.add(tuple((r, p) for _, r, p in world(costs, sigma, 0.5 * g2, tau)))
        for seq in gen:
            pairs = [(c, r, p) for c, (r, p) in zip(costs, seq)]
            assert single_floor_fit(pairs)[0], f"a generated sequence was rejected: {pairs}"
            n_gen += 1
            flat = [v for pr in seq for v in pr]
            if any((not np.isfinite(v)) or (not float(v).is_integer()) or abs(v) > 5 for v in flat):
                continue
            for i, dlt in itertools.product(range(len(flat)), (-1.0, 1.0)):
                f2 = list(flat)
                f2[i] += dlt
                seq2 = tuple((f2[2 * k], f2[2 * k + 1]) for k in range(len(costs)))
                got = single_floor_fit([(c, r, p) for c, (r, p) in zip(costs, seq2)])[0]
                assert got == (seq2 in gen), f"exact test disagrees with the brute force on {seq2} at costs {costs}"
                n_pert += 1
    print(f"8 ok: exact test agrees with the brute force on {n_gen} generated and {n_pert} perturbed sequences")


def review_cases():
    """9. Cases from the fourth AI-assisted review (theory_audit.py): which violations a reward-only test can see."""
    costs = [0.0, 1.0, 2.0]
    pairs = lambda f: [(c, f(1, c), f(-1, c)) for c in costs]  # noqa: E731
    seen = {"cost-dependent floor": pairs(lambda s, c: max(s * 10 - c, c)),
            "incompatible grid": [(0.0, 10.0, -10.0), (1.0, 0.0, 0.0)]}
    unseen = {"hidden fixed fee, censored loss branch": pairs(lambda s, c: max(s * 10 - c - 7, 0.0)),
              "inflated gross credit": pairs(lambda s, c: max(s * 15 - c, 0.0)),
              "constant output (two censors)": pairs(lambda s, c: min(max(s * 10 - c, 2.0), 2.0))}
    for name, pr in seen.items():
        assert cost_shift_test(pr)[0], f"exact test missed {name}"
        assert not cost_shift_test(pr, exact=False)[0], f"the implied-conditions check was expected to miss {name}"
    for name, pr in unseen.items():
        ok, wit, _ = single_floor_fit(pr)
        assert ok and wit is not None, f"{name} should be reproducible by a single-floor world"
    both = [(c, -3.0 - c, -23.0 - c) for c in costs]                     # hidden fee 7 on g = 10 with both branches uncensored
    assert cost_shift_test(both)[0], "a hidden fixed fee with both branches uncensored should be flagged (u + l = -2(c + fee))"
    print(f"9 ok: flagged {sorted(seen)} and an uncensored hidden fee; reproducible by a single floor, hence unflagged: {sorted(unseen)}")


def pmr_bias_case():
    """10. PMR's bias with a pool of censored favourable draws: q = 1, m = 1, c = 1, tau = 10, P(favourable) = 0.75."""

    class Censored(gym.Env):
        metadata: dict = {}

        def __init__(self):
            self.action_space = gym.spaces.Discrete(1)
            self.observation_space = gym.spaces.Box(-np.inf, np.inf, (1,), dtype=np.float32)
            self.sigma = 1.0

        def step(self, action):
            x = self.sigma * 1.0 - 1.0
            return np.zeros(1, np.float32), max(x, 10.0), False, False, {"gross_sign": self.sigma, "position": 1.0, "own_cost": 1.0, "booked": x}

    w = PooledMagnitudeWrapper(Censored())
    w.step(0)                                                            # one favourable draw enters the pool: U = (10 + 1) / 1 = 11
    vals = {}
    for s in (1.0, -1.0):
        branch = copy.deepcopy(w)
        branch.env.sigma = s
        _, rhat, _, _, info = branch.step(0)
        vals[s] = (rhat, info["booked"], info["pooled_magnitude"])
    e_pmr = 0.75 * vals[1.0][0] + 0.25 * vals[-1.0][0]
    e_booked = 0.75 * vals[1.0][1] + 0.25 * vals[-1.0][1]
    assert abs(e_pmr - 4.5) < 1e-12 and abs(e_booked + 0.5) < 1e-12, (e_pmr, e_booked)
    d, mu, m_bar = 0.5, 1.0, vals[1.0][2]
    assert abs((e_pmr - e_booked) - 1.0 * d * (m_bar - mu)) < 1e-12, "bias identity |q| d (m_bar - mu) violated"
    print(f"10 ok: PMR with a censored pool: expected reward {e_pmr:+.2f} against booked {e_booked:+.2f} (bias identity holds)")


def bracket_checks(rng):
    """11. The twin bracket contains the booked P&L on the single-floor AND the two-write toy (no single-floor assumption), its width is the
    total credit of the pair, and SPR is its midpoint."""
    n_exact = n_steps = 0
    for cls in (ToyFloorEnv, ToyTwoWriteEnv):
        for _ in range(3000):
            env = cls(seed=int(rng.integers(1e9)), fee=0.1, kappa=0.02)
            env.reset()
            env.equity = float(rng.choice([0.0, 1e-3, 0.02, 0.1, 0.5, 2.0, 50.0]))
            a = int(rng.integers(0, len(LEV)))
            real, twin = copy.deepcopy(env), copy.deepcopy(env)
            twin.reverse_next_sign()
            _, r, _, _, info = real.step(a)
            _, rt, _, _, info_t = twin.step(a)
            c, b, bt = info["own_cost"], info["booked"], info_t["booked"]
            lo, hi = twin_bracket(r, rt, c)
            assert lo - 1e-9 <= b <= hi + 1e-9, f"{cls.__name__}: booked {b} outside [{lo}, {hi}]"
            assert abs((hi - lo) - ((r - b) + (rt - bt))) < 1e-9, "width is not the total credit of the pair"
            assert abs(0.5 * (lo + hi) - float(spr(r, rt, c))) < 1e-12, "SPR is not the midpoint"
            n_steps += 1
            n_exact += int(hi - lo < 1e-12)
    print(f"11 ok: twin bracket contained the booked P&L on {n_steps} steps of the single-floor and two-write toys ({n_exact} exact)")


def main():
    rng = np.random.default_rng(0)
    n = n_id = 0
    for est in ("tir", "spr"):
        plain, wrapped = ToyFloorEnv(seed=5), TwinRewardWrapper(ToyFloorEnv(seed=5), est)
        o1, _ = plain.reset(seed=5)
        o2, _ = wrapped.reset(seed=5)
        for _ in range(3000):
            a = int(rng.integers(0, len(LEV)))
            o1, r1, *_ = plain.step(a)
            o2, rhat, _, _, info = wrapped.step(a)
            assert np.allclose(o1, o2) and r1 == info["reported_reward"], "the wrapper changed the real trajectory"
            b, c, r, rt = info["booked"], info["own_cost"], info["reported_reward"], info["twin_reward"]
            assert r >= b - 1e-12, "reported reward below booked P&L"
            if est == "tir":
                n += 1
                if info["identified"]:
                    n_id += 1
                    assert abs(rhat - b) < 1e-9, "TIR not exact on an identified step"
                else:
                    assert abs(rhat + c) < 1e-9, "TIR must be -c where the pair coincides"
                assert abs(rhat - b) <= abs(spr(r, rt, c) - b) + 1e-9, "TIR errs more than SPR"
    print(f"1-3 ok: {n} steps, {n_id} identified ({100 * n_id / n:.0f}%)")

    worst = 0.0
    for _ in range(3000):
        env = ToyFloorEnv(seed=int(rng.integers(1e9)))
        env.reset()
        a = int(rng.integers(0, len(LEV)))
        for est in ("tir", "spr"):
            vals = []
            for s in (-1.0, 1.0):
                e = copy.deepcopy(env)
                e.force_sign = s
                w = TwinRewardWrapper(e, est)
                _, rhat, _, _, info = w.step(a)
                vals.append(rhat)
            c = info["own_cost"]
            m = np.mean(vals)
            expected = -c                                           # E[b] = -c in a fair market
            if est == "tir":
                worst = max(worst, abs(m - expected))
                assert abs(m - expected) < 1e-9, f"TIR is not fair-unbiased: {m} vs {expected}"
            # SPR is fair-unbiased too (Proposition S, part 1 with p = 1/2)
            assert abs(m - expected) < 1e-9, f"{est} is not fair-unbiased: {m} vs {expected}"
    print(f"4 ok: fair-sign expectation equals -c to {worst:.1e}")

    # 6. clone-free pooled-magnitude reward: leaves the trajectory untouched, fair-sign expectation -c in every state (also credited ones),
    #    pooled mean close to E[m] = 0.3 sqrt(2/pi), reward noise on the magnitude only.
    plain, pmr_env = ToyFloorEnv(seed=9, fee=0.01, kappa=0.0005), PooledMagnitudeWrapper(ToyFloorEnv(seed=9, fee=0.01, kappa=0.0005))
    plain.reset(seed=9)
    pmr_env.reset(seed=9)
    for _ in range(30000):
        a = int(rng.integers(0, len(LEV)))
        o1, r1, *_ = plain.step(a)
        o2, rhat, _, _, info = pmr_env.step(a)
        assert np.allclose(o1, o2) and r1 == info["reported_reward"], "PMR wrapper changed the real trajectory"
    m_true = 0.3 * np.sqrt(2 / np.pi)
    m_bar = pmr_env.total / pmr_env.n
    assert -0.01 * m_true < m_bar - m_true < 0.05 * m_true, f"pooled mean {m_bar} not in [E[m], 1.05 E[m]] ({m_true})"      # censoring can only raise it
    worst_pmr = 0.0
    for _ in range(2000):
        env = ToyFloorEnv(seed=int(rng.integers(1e9)))
        env.reset()
        env.equity = 0.0 if rng.random() < 0.5 else env.equity                     # include states where a credit is certain
        a = int(rng.integers(0, len(LEV)))
        vals = []
        for s in (-1.0, 1.0):
            e = copy.deepcopy(env)
            e.force_sign = s
            w = PooledMagnitudeWrapper(e)
            w.total, w.n = 0.25 * 50, 50                                           # any pooled mean
            _, rhat, _, _, info = w.step(a)
            vals.append(rhat)
        worst_pmr = max(worst_pmr, abs(np.mean(vals) + info["own_cost"]))
        assert abs(np.mean(vals) + info["own_cost"]) < 1e-9, "PMR is not fair-unbiased"
    print(f"6 ok: PMR pooled mean {m_bar:.4f} vs E[m] {m_true:.4f}; fair-sign expectation equals -c to {worst_pmr:.1e}")

    cost_shift_checks(rng)
    exactness_checks()
    review_cases()
    pmr_bias_case()
    bracket_checks(rng)

    ids = identified(np.array([1.0, 2.0]), np.array([1.0, 3.0]))
    assert list(ids) == [False, True] and list(tir([1.0, 3.0], [1.0, 2.0], [0.5, 0.5])) == [-0.5, 1.0 * (3.0 + 0.5) - 0.5]
    print("5 ok: estimator helpers")
    print("all checks pass")


if __name__ == "__main__":
    main()
