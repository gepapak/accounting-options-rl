"""Exact test of Assumption C on cost-shifted twin pairs (development version; merged into twin_reward.py once validated).

Assumption C: the reward of a step is r = max(sigma*g - c, tau), with a gross magnitude g >= 0 and a threshold tau that depend neither on the
sign sigma nor on the own cost c (the twin step has the sign -sigma). Fix ONE state, action and exogenous draw, shift the own cost over
c_1, ..., c_K and record the pairs (c_k, r_k, r'_k). The pairs are *generated by a single-floor world* iff there are sigma in {+1, -1}, g >= 0
and tau in [-inf, inf) with

    r_k = max(sigma*g - c_k, tau)   and   r'_k = max(-sigma*g - c_k, tau)          for every k.

`single_floor_fit` decides this exactly. Write u_k for the reward of the favourable branch (the one with sign +1 in the model) and l_k for the
other. A candidate (g, tau) can be restricted to a finite set: if some favourable branch is uncensored then g = u_k + c_k (and, if the
unfavourable branch is uncensored too, also g = -l_k - c_k); if every favourable branch is censored then g = 0 reproduces the pairs whenever any
g does (g = 0 gives max(-c_k, tau) = tau wherever tau >= g - c_k >= -c_k); and tau is either -inf (nothing is censored) or the common value of a
censored branch, hence one of the observed rewards. So it suffices to try g in {0} + {u_k + c_k} + {-l_k - c_k} and tau in {-inf} + {u_k} + {l_k},
for each of the two assignments of the branches. The previous test (twin_reward.cost_shift_test) checks only some consequences of this (the
inferred magnitude is constant where the pair is unequal; the censored value is constant) and misses, for example, a threshold that moves with
the cost on the unfavourable branch.

What the test cannot see: a world that is not a single-floor world but produces pairs that one could have produced (a hidden fixed fee,
an inflated gross credit, a constant reward). Those are invisible to every method that uses only the pairs and the declared costs.
"""
from __future__ import annotations

import numpy as np


def single_floor_fit(pairs, tol: float = 1e-9):
    """pairs: iterable of (cost, r, r_twin) at one state, action and exogenous draw. Returns (consistent, witness, detail).

    consistent  True iff some single-floor world (sigma, g, tau) reproduces every pair to within tol * scale (scale = 1 + largest |value|).
    witness     (sigma, g, tau) of one reproducing world (the real step has the favourable branch iff sigma = +1), or None.
    detail      a short reason when inconsistent (which structural property fails, and the best residual of any candidate world).
    """
    data = sorted((float(c), float(r), float(p)) for c, r, p in pairs)
    if not data:
        return True, None, "no pairs"
    c = np.array([d[0] for d in data])
    r = np.array([d[1] for d in data])
    p = np.array([d[2] for d in data])
    scale = 1.0 + float(np.max(np.abs(np.concatenate([c, r, p]))))
    eps = tol * scale
    d = r - p
    if np.any(d > eps) and np.any(d < -eps):
        return False, None, "the branch with the larger reward changes with the cost"
    best = (np.inf, None)
    for sigma in (+1.0, -1.0):
        u, l = (r, p) if sigma > 0 else (p, r)                      # favourable and unfavourable reward under this assignment
        G = np.unique(np.concatenate(([0.0], u + c, -l - c)))
        G = np.maximum(G[G >= -eps], 0.0)
        T = np.concatenate(([-np.inf], u, l))
        pu = np.maximum(G[:, None, None] - c[None, None, :], T[None, :, None])            # predicted favourable rewards
        pl = np.maximum(-G[:, None, None] - c[None, None, :], T[None, :, None])           # predicted unfavourable rewards
        res = np.maximum(np.abs(pu - u).max(axis=2), np.abs(pl - l).max(axis=2))          # worst misfit over the costs, per (g, tau)
        i, j = np.unravel_index(int(np.argmin(res)), res.shape)
        if res[i, j] < best[0]:
            best = (float(res[i, j]), (sigma, float(G[i]), float(T[j])))
        if res[i, j] <= eps:
            return True, (sigma, float(G[i]), float(T[j])), "consistent with a single monotone censor"
    return False, None, f"no single (g, tau) reproduces the pairs (best misfit {best[0]:.3g} against tolerance {eps:.3g})"
